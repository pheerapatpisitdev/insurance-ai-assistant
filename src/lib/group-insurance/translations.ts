export const translations: Record<Lang, Record<Key, string>> = { th, en };

/** The word for `key`, or the key itself — a missing word is better than an empty space. */
export function translator(lang: Lang) {
  const table = translations[lang];
  return (key: Key): string => table[key] ?? key;
}

/** Thai digits group the same way, but the month names and the era do not. */
export function localeOf(lang: Lang): string {
  return lang === "en" ? "en-US" : "th-TH";
}
